# Office formats Quick Look renders to HTML (xlsx/xls: every sheet, with tabs, formatting kept).
QUICKLOOK_HTML = {".docx", ".pptx", ".xlsx", ".xls"}
QUICKLOOK_MAX_ROWS = 4000   # Quick Look silently cuts sheets at ~4096 rows (CSV at 10000)
GRID_MAX_CELLS = 500_000    # our own grid view: beyond this, show the first rows and say so
PANDOC_HTML = {".odt": "odt", ".rtf": "rtf", ".epub": "epub", ".ipynb": "ipynb", ".tex": "latex"}


# -- text layers -----------------------------------------------------------------
def text_layer(fid: str, index: int) -> dict:
    """Text runs of page `index` as fractions of the page, top-left origin:
    {"source": "pdf"|"ocr", "lines": [{"t", "x", "y", "w", "h", "nl"}]}. `nl` marks the start of a new line."""
    meta = docs.get(fid)
    cache = docs.FILES_DIR / fid / f"text-{index + 1:04d}.json"
    if cache.exists():
        return json.loads(cache.read_text())
    out = _pdf_runs(fid, index) if meta["kind"] == "pdf" else None
    if out is None:
        out = _ocr_lines(docs.page_image(fid, index, 200))
    cache.write_text(json.dumps(out, ensure_ascii=False))
    return out


def _pdf_runs(fid: str, index: int) -> dict | None:
    """Group pdfium's characters into runs (same baseline, no wide gap). None if the page needs OCR."""
    with docs._render_lock:
        pdf = pdfium.PdfDocument(str(docs.source_path(fid)))
        try:
            page = pdf[index]
            if page.get_rotation():
                return None  # char boxes are unrotated; let OCR read the rendered (rotated) image
            cl, cb, cr, ct = page.get_cropbox()
            W, H = cr - cl, ct - cb
            tp = page.get_textpage()
            runs, cur = [], None
            for i in range(tp.count_chars()):
                ch = chr(pdfium_c.FPDFText_GetUnicode(tp, i))
                if ch in "\r\n\x00\ufffe" or pdfium_c.FPDFText_IsGenerated(tp, i) == 1 and ch != " ":
                    cur = None
                    continue
                if ch == " ":  # often generated by pdfium, without a box of its own
                    if cur:
                        cur["s"] += " "
                    continue
                try:
                    l, b, r, t = tp.get_charbox(i, loose=True)
                except pdfium.PdfiumError:
                    continue
                h = t - b
                if h <= 0:
                    continue
                if cur and abs(b - cur["b"]) < h * 0.4 and -h * 0.5 < l - cur["r"] < h * 1.2:
                    cur["s"] += ch
                    cur["r"], cur["t"] = max(cur["r"], r), max(cur["t"], t)
                    continue
                newline = not runs or abs(b - runs[-1]["b"]) >= h * 0.4
                cur = {"s": ch, "l": l, "b": b, "r": r, "t": t, "nl": newline}
                runs.append(cur)
            if sum(len(r["s"].strip()) for r in runs) < 10:
                return None  # scanned page (or nearly empty): OCR it instead
        finally:
            pdf.close()
    return {"source": "pdf", "lines": [
        {"t": r["s"].rstrip(), "x": (r["l"] - cl) / W, "y": (ct - r["t"]) / H, "w": (r["r"] - r["l"]) / W,
         "h": (r["t"] - r["b"]) / H, "nl": r["nl"]} for r in runs if r["s"].strip()]}


def _ocr_lines(img: Path) -> dict:
    av = ENGINES["apple-vision"]
    av.ensure_binary()
    r = subprocess.run([str(av.binary), "--mode", "text", "--boxes", str(img)],
                       capture_output=True, text=True, timeout=120)
    d = json.loads(r.stdout.splitlines()[0]) if r.stdout.strip() else {"error": r.stderr[-500:]}
    if d.get("error"):
        raise RuntimeError(d["error"])
    return {"source": "ocr", "lines": [{**ln, "nl": True} for ln in d["lines"]]}


# -- HTML views --------------------------------------------------------------------
def html_view(fid: str) -> dict:
    """Render an Office/text file to HTML once; returns {"entry": relative path, "scripts": bool}."""
    meta = docs.get(fid)
    vdir = docs.FILES_DIR / fid / "view"
    info = vdir / "view.json"
    if info.exists():
        return json.loads(info.read_text())
    src = docs.source_path(fid)
    ext = meta["ext"]
    tmp = Path(tempfile.mkdtemp(dir=docs.FILES_DIR / fid))
    try:
        out = None
        if ext == ".csv" or ext in (".xlsx", ".xls") and _max_rows(src) > QUICKLOOK_MAX_ROWS:
            out = _grid_html(src, tmp, meta["name"])
        elif ext in QUICKLOOK_HTML:
            out = _quicklook_html(src, tmp)
        elif ext in (".html", ".htm"):
            shutil.copy(src, tmp / "index.html")
            out = {"entry": "index.html", "scripts": False}  # someone else's page: no scripts
        elif ext in PANDOC_HTML and convert.PANDOC:
            out = _pandoc_html(src, PANDOC_HTML[ext], tmp, meta["name"])
        if out is None:  # e.g. .msg, or a renderer that failed: MarkItDown's Markdown, rendered
            from markitdown import MarkItDown
            md = MarkItDown().convert(str(src)).markdown
            (tmp / "index.html").write_text(convert.to_html(md, meta["name"]))
            out = {"entry": "index.html", "scripts": False}
        (tmp / "view.json").write_text(json.dumps(out))
        shutil.rmtree(vdir, ignore_errors=True)
        tmp.rename(vdir)
        return out
    finally:
        shutil.rmtree(tmp, ignore_errors=True)


# Injected into Quick Look's pages: fit fixed-width slides/pages to the pane, and apply the viewer's zoom
# (sent by postMessage, since the sandboxed frame can't be reached directly; forwarded to sheet frames).
FIT_JS = """<script>(() => {
  let z = 1;
  const fit = () => {
    const w = +((document.querySelector("meta[name=viewport]")?.content || "").match(/width=(\\d+)/) || [])[1] || 0;
    const outer = document.querySelector("iframe");  // a tab container: its sheet frames do the zooming
    document.documentElement.style.zoom = (w && innerWidth < w ? innerWidth / w : 1) * (outer ? 1 : z);
  };
  const send = (f) => f.contentWindow?.postMessage({ zoom: z }, "*");
  addEventListener("resize", fit);
  addEventListener("message", (e) => {
    if (typeof e.data?.zoom !== "number") return;
    z = e.data.zoom; fit(); document.querySelectorAll("iframe").forEach(send);
  });
  addEventListener("DOMContentLoaded", () => {
    fit(); document.querySelectorAll("iframe").forEach((f) => f.addEventListener("load", () => send(f)));
  });
})()</script>"""


def _quicklook_html(src: Path, tmp: Path) -> dict | None:
    subprocess.run(["qlmanage", "-p", "-o", str(tmp), str(src)], capture_output=True, timeout=120)
    ql = tmp / f"{src.name}.qlpreview"
    if not (ql / "Preview.html").exists():
        shutil.rmtree(ql, ignore_errors=True)
        return None
    for p in ql.iterdir():
        if p.suffix == ".html":
            p.write_text(p.read_text().replace("<head>", "<head>" + FIT_JS, 1))
        p.rename(tmp / p.name)
    ql.rmdir()
    return {"entry": "Preview.html", "scripts": True}  # sheet tabs are driven by Quick Look's own script


def _pandoc_html(src: Path, reader: str, tmp: Path, title: str) -> dict | None:
    r = subprocess.run([convert.PANDOC, "-f", reader, "-t", "html5", "-s", "--embed-resources", "--mathml",
                        "--metadata", f"pagetitle={title}", str(src)],
                       capture_output=True, text=True, timeout=120, cwd=src.parent)
    if r.returncode:
        return None
    light = "html{color-scheme:light;background:#fff}"  # pandoc's template goes dark; page images don't
    page = r.stdout.replace("</head>", f"<style>{convert.CSS}{light}</style></head>", 1)
    (tmp / "index.html").write_text(page)
    return {"entry": "index.html", "scripts": False}


# -- spreadsheets: every row, values only ----------------------------------------------
def _sheets(src: Path):
    """Yield (sheet name, row count or None, row iterator) for csv/xlsx/xls."""
    ext = src.suffix.lower()
    if ext == ".csv":
        raw = src.read_bytes()
        try:
            text = raw.decode("utf-8-sig")
        except UnicodeDecodeError:
            text = raw.decode("cp1252", errors="replace")
        try:
            dialect = csv.Sniffer().sniff(text[:20000], delimiters=",;\t|")
        except csv.Error:
            dialect = csv.excel
        rows = list(csv.reader(io.StringIO(text), dialect))
        yield src.stem, len(rows), iter(rows)
    elif ext == ".xls":
        import xlrd
        for sh in xlrd.open_workbook(str(src), on_demand=True).sheets():
            yield sh.name, sh.nrows, (sh.row_values(i) for i in range(sh.nrows))
    else:
        import openpyxl
        wb = openpyxl.load_workbook(str(src), read_only=True, data_only=True)
        for ws in wb.worksheets:
            yield ws.title, ws.max_row, ws.iter_rows(values_only=True)


def _max_rows(src: Path) -> int:
    try:
        return max((n or 0 for _, n, _ in _sheets(src)), default=0)
    except Exception:
        return 0


def _col(i: int) -> str:
    s = ""
    i += 1
    while i:
        i, r = divmod(i - 1, 26)
        s = chr(65 + r) + s
    return s


def _cell(v) -> str:
    if v is None:
        return ""
    if isinstance(v, float) and v.is_integer():
        v = int(v)
    return html.escape(str(v))


def _grid_html(src: Path, tmp: Path, title: str) -> dict:
    tabs, panes = [], []
    for k, (name, total, rows) in enumerate(_sheets(src)):
        body, width, n = [], 0, 0
        for row in rows:
            row = list(row)
            while row and row[-1] in (None, ""):
                row.pop()
            width = max(width, len(row))
            n += 1
            if width and n * width > GRID_MAX_CELLS:
                break
            body.append(f"<tr><th>{n}</th>" + "".join(f"<td>{_cell(v)}</td>" for v in row) + "</tr>")
        shown = len(body)
        note = (f'<p class="note">Showing the first {shown:,} of {total or shown:,} rows. Open the original for '
                f'the rest.</p>' if total and shown < total else "")
        head = "<tr><th></th>" + "".join(f"<th>{_col(i)}</th>" for i in range(width)) + "</tr>"
        hidden = "" if k == 0 else " hidden"
        panes.append(f'<section{hidden}>{note}<table><thead>{head}</thead><tbody>{"".join(body)}</tbody></table></section>')
        tabs.append(f'<button{" class=on" if k == 0 else ""}>{html.escape(name)}</button>')
    nav = f'<nav>{"".join(tabs)}</nav>' if len(tabs) > 1 else ""
    page = f"""<!doctype html><html><head><meta charset="utf-8">{FIT_JS}<title>{html.escape(title)}</title><style>
body {{ margin: 0; font: 12px -apple-system, sans-serif; color: #1d1d1f; background: #fff; }}
table {{ border-collapse: collapse; }}
td, th {{ border: 1px solid #e3e3e8; padding: 2px 6px; white-space: nowrap; }}
td {{ max-width: 40em; overflow: hidden; text-overflow: ellipsis; }}
th {{ background: #f2f2f5; color: #6e6e76; font-weight: normal; position: sticky; user-select: none; }}
thead th {{ top: 0; z-index: 1; }}
tbody th {{ left: 0; text-align: right; }}
thead th:first-child {{ left: 0; z-index: 2; }}
nav {{ position: sticky; bottom: 0; display: flex; gap: 2px; background: #e5e5ea; padding: 3px 4px; z-index: 3; }}
nav button {{ border: 0; background: none; padding: 3px 10px; border-radius: 4px; font: inherit; cursor: pointer; }}
nav button.on {{ background: #fff; font-weight: 600; }}
.note {{ margin: 0; padding: 6px 8px; background: #fff8e1; position: sticky; left: 0; }}
section {{ min-height: calc(100vh - 30px); }}
</style></head><body>{"".join(panes)}{nav}<script>
document.querySelectorAll("nav button").forEach((b, i) => b.onclick = () => {{
  document.querySelectorAll("section").forEach((s, j) => s.hidden = i !== j);
  document.querySelectorAll("nav button").forEach((x) => x.classList.toggle("on", x === b));
}});
</script></body></html>"""
    (tmp / "index.html").write_text(page)
    return {"entry": "index.html", "scripts": True}


def view_file(fid: str, rel: str) -> Path:
    vdir = (docs.FILES_DIR / fid / "view").resolve()
    p = (vdir / rel).resolve()
    if vdir not in p.parents or not p.is_file():
        raise KeyError(rel)
    return p
